-- QUESTION_1: What are the overall totals (customers, revenue, avg order)?
SELECT COUNT(*)                          AS total_customers,
       SUM(purchase_amount)              AS total_revenue,
       ROUND(AVG(purchase_amount), 2)   AS avg_order_value,
       ROUND(AVG(review_rating), 2)     AS avg_rating
FROM customer;


-- QUESTION_2: What is the distribution of customers across age groups?
SELECT age_group, COUNT(*) AS customers
FROM customer
GROUP BY age_group
ORDER BY customers DESC;


-- QUESTION_3: How many customers are in each gender?
SELECT gender, COUNT(*) AS customers
FROM customer
GROUP BY gender;


-- QUESTION_4: What are the 10 most purchased products (by order count)?
SELECT item_purchased,
       COUNT(*)                        AS orders,
       SUM(purchase_amount)            AS revenue
FROM customer
GROUP BY item_purchased
ORDER BY orders DESC
LIMIT 10;


-- QUESTION_5: What is the average purchase amount, min, and max?
SELECT ROUND(AVG(purchase_amount), 2) AS avg_spend,
       MIN(purchase_amount)            AS min_spend,
       MAX(purchase_amount)            AS max_spend,
       ROUND(STDDEV(purchase_amount), 2) AS std_dev_spend
FROM customer;


-- QUESTION_6: How many customers used each shipping type?
SELECT shipping_type,
       COUNT(*) AS customers,
       ROUND(AVG(purchase_amount), 2) AS avg_spend
FROM customer
GROUP BY shipping_type
ORDER BY customers DESC;


-- QUESTION_7: What are the most common colors purchased?
SELECT color,
       COUNT(*) AS orders
FROM customer
GROUP BY color
ORDER BY orders DESC
LIMIT 10;


-- QUESTION_8: What is the review rating distribution (how many 1-star, 2-star, etc.)?
SELECT ROUND(review_rating, 0)  AS rating_bucket,
       COUNT(*)                 AS customers
FROM customer
GROUP BY ROUND(review_rating, 0)
ORDER BY rating_bucket;

