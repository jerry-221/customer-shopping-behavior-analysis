-- QUESTION_2: What is each region's share of total revenue (percentage)?
SELECT region,
       SUM(purchase_amount)            AS revenue,
       ROUND(100.0 * SUM(purchase_amount)
             / (SELECT SUM(purchase_amount) FROM customer), 2) AS pct_of_total
FROM customer
GROUP BY region
ORDER BY revenue DESC;


-- QUESTION_3: How does avg spend evolve across loyalty tiers (with rank)?
SELECT loyalty_tier,
       COUNT(*)                        AS customers,
       ROUND(AVG(purchase_amount), 2) AS avg_spend,
       ROUND(AVG(customer_lifetime_value), 2) AS avg_clv,
       ROUND(AVG(review_rating), 2)   AS avg_rating
FROM customer
GROUP BY loyalty_tier
ORDER BY avg_clv DESC;


-- QUESTION_4: Which products have above-average revenue AND above-average rating?
WITH product_stats AS (
    SELECT item_purchased,
           SUM(purchase_amount)            AS revenue,
           AVG(review_rating)              AS avg_rating
    FROM customer
    GROUP BY item_purchased
),
overall_avg AS (
    SELECT AVG(revenue) AS avg_rev,
           AVG(avg_rating) AS avg_rate
    FROM product_stats
)
SELECT p.item_purchased, p.revenue, ROUND(p.avg_rating, 2) AS avg_rating
FROM product_stats p
CROSS JOIN overall_avg o
WHERE p.revenue    > o.avg_rev
  AND p.avg_rating > o.avg_rate
ORDER BY p.revenue DESC;


-- QUESTION_5: Which customers rank in the top 10% by lifetime value?
WITH ranked AS (
    SELECT customer_id, age_group, region, loyalty_tier,
           customer_lifetime_value,
           NTILE(10) OVER (ORDER BY customer_lifetime_value DESC) AS decile
    FROM customer
)
SELECT customer_id, age_group, region, loyalty_tier, customer_lifetime_value
FROM ranked
WHERE decile = 1
ORDER BY customer_lifetime_value DESC
LIMIT 20;


-- QUESTION_6: What is the purchase frequency breakdown per loyalty tier?
SELECT loyalty_tier,
       ROUND(AVG(purchase_frequency_days), 1) AS avg_days_between_orders,
       ROUND(AVG(total_purchases), 1)         AS avg_total_purchases,
       COUNT(*) AS customers
FROM customer
GROUP BY loyalty_tier
ORDER BY avg_days_between_orders;


-- QUESTION_7: Which payment method is preferred by each age group?
SELECT age_group,
       payment_category,
       COUNT(*) AS customers,
       ROUND(100.0 * COUNT(*) /
             SUM(COUNT(*)) OVER (PARTITION BY age_group), 1) AS pct_within_age
FROM customer
GROUP BY age_group, payment_category
ORDER BY age_group, customers DESC;


-- QUESTION_8: What % of each region's customers are subscribed?
SELECT region,
       COUNT(*)                                        AS customers,
       SUM(is_subscriber)                              AS subscribers,
       ROUND(100.0 * SUM(is_subscriber) / COUNT(*), 1) AS pct_subscribed
FROM customer
GROUP BY region
ORDER BY pct_subscribed DESC;


-- QUESTION_9: Which customers churn-risk (low frequency × low spend) — the "at-risk" segment?
SELECT customer_id, age_group, region, purchase_amount,
       purchase_frequency_days, previous_purchases
FROM customer
WHERE purchase_frequency_days > 90          -- purchases less often than quarterly
  AND purchase_amount < (SELECT AVG(purchase_amount) FROM customer)  -- and low spend
  AND previous_purchases <= 5               -- and relatively new
ORDER BY purchase_amount DESC
LIMIT 50;


-- QUESTION_10: Which products have both high revenue and high discount dependence?
WITH metrics AS (
    SELECT item_purchased,
           SUM(purchase_amount) AS revenue,
           ROUND(100.0 * AVG(is_discount_user), 1) AS discount_pct
    FROM customer
    GROUP BY item_purchased
)
SELECT item_purchased, revenue, discount_pct
FROM metrics
WHERE revenue      > (SELECT AVG(revenue) FROM metrics)
  AND discount_pct > 50
ORDER BY revenue DESC;


-- QUESTION_11: What is the revenue trend across age × gender combos for heatmap visualisation?
SELECT age_group,
       SUM(CASE WHEN gender = 'Male'   THEN purchase_amount ELSE 0 END) AS revenue_male,
       SUM(CASE WHEN gender = 'Female' THEN purchase_amount ELSE 0 END) AS revenue_female,
       SUM(purchase_amount)                                            AS revenue_total
FROM customer
GROUP BY age_group
ORDER BY revenue_total DESC;






