-- QUESTION_1: Which gender × age group combination generates the most revenue?
SELECT gender,
       age_group,
       COUNT(*)                        AS customers,
       SUM(purchase_amount)            AS revenue,
       ROUND(AVG(purchase_amount), 2) AS avg_spend
