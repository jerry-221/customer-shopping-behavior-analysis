-- QUESTION_1: What is the total revenue generated by male vs female customers?
SELECT gender,                          
       SUM(purchase_amount)  AS revenue,   
       COUNT(*)               AS customers, 
       ROUND(AVG(purchase_amount), 2) AS avg_spend  
FROM customer                           
GROUP BY gender;                       


-- QUESTION_2: Which customers used a discount but still spent above the average purchase amount?
SELECT customer_id,                    
       purchase_amount,                 
       discount_applied                 
FROM customer
WHERE discount_applied = 'Yes'          
  AND purchase_amount > (               
      SELECT AVG(purchase_amount)       
      FROM customer
  );



-- QUESTION_3: Which are the top 5 products with the highest average review rating?
SELECT item_purchased,                  
       ROUND(AVG(review_rating), 2) AS avg_rating,  
       COUNT(*)                     AS review_count 
FROM customer
GROUP BY item_purchased
ORDER BY avg_rating DESC                
LIMIT 5;             


-- QUESTION_4: Do Express shipping customers spend more than Standard shipping customers?
SELECT shipping_type,                    
       ROUND(AVG(purchase_amount), 2) AS avg_spend,
       COUNT(*)                        AS orders
FROM customer
WHERE shipping_type IN ('Standard', 'Express')  
GROUP BY shipping_type;                   


-- QUESTION_5: Do subscribed customers spend more than non-subscribed customers?
SELECT subscription_status,            
       COUNT(*)                        AS customers,
       ROUND(AVG(purchase_amount), 2) AS avg_spend,
       SUM(purchase_amount)            AS total_revenue
FROM customer
GROUP BY subscription_status
ORDER BY total_revenue DESC;


-- QUESTION_6: Which 5 products have the highest percentage of purchases with a discount applied?
SELECT item_purchased,
       ROUND(
           100.0 * SUM(CASE WHEN discount_applied = 'Yes' THEN 1 ELSE 0 END)
                 / COUNT(*),
           1
       ) AS discount_rate_pct,
       COUNT(*) AS order_count
FROM customer
GROUP BY item_purchased
ORDER BY discount_rate_pct DESC
LIMIT 5;


-- QUESTION_7: How many customers are in each loyalty tier, and what's their average spend?
SELECT loyalty_tier,
       COUNT(*)                        AS customers,
       ROUND(AVG(purchase_amount), 2) AS avg_spend
FROM customer
GROUP BY loyalty_tier
ORDER BY customers DESC;


-- QUESTION_8: What are the top 3 most purchased products within each category?
WITH ranked AS (                             
    SELECT category,
           item_purchased,
           COUNT(*) AS total_orders,
           ROW_NUMBER() OVER (                
               PARTITION BY category          
               ORDER BY COUNT(*) DESC         
           ) AS rn
    FROM customer
    GROUP BY category, item_purchased         
)
SELECT category, item_purchased, total_orders
FROM ranked
WHERE rn <= 3                                 
ORDER BY category, rn;


-- QUESTION_9: Are repeat buyers (previous_purchases > 5) also likely to be subscribers?
SELECT subscription_status,
       COUNT(*) AS repeat_buyers
FROM customer
WHERE previous_purchases > 5
GROUP BY subscription_status;


-- QUESTION_10: Which age group generates the most revenue?
SELECT age_group,
       COUNT(*)                        AS customers,
       SUM(purchase_amount)            AS revenue,
       ROUND(AVG(purchase_amount), 2) AS avg_spend
FROM customer
GROUP BY age_group
ORDER BY revenue DESC;


-- QUESTION_11: Which US region generates the most revenue, and how does spend per customer compare?
SELECT region,
       COUNT(*)                        AS customers,
       SUM(purchase_amount)            AS revenue,
       ROUND(AVG(purchase_amount), 2) AS avg_spend
FROM customer
GROUP BY region
ORDER BY revenue DESC;


-- QUESTION_12: Which season drives the highest revenue and spend?
SELECT season,
       COUNT(*)                        AS orders,
       SUM(purchase_amount)            AS revenue,
       ROUND(AVG(purchase_amount), 2) AS avg_spend
FROM customer
GROUP BY season
ORDER BY revenue DESC;


-- QUESTION_13: What share of revenue comes from each payment type (digital wallet, card, cash, bank)?
SELECT payment_category,
       COUNT(*)                        AS customers,
       SUM(purchase_amount)            AS revenue,
       ROUND(AVG(purchase_amount), 2) AS avg_spend
FROM customer
GROUP BY payment_category
ORDER BY revenue DESC;


-- QUESTION_14: Do discounts increase or decrease the average order value per category?
SELECT category,
       ROUND(AVG(CASE WHEN discount_applied = 'Yes'
                      THEN purchase_amount END), 2) AS avg_with_discount,
       ROUND(AVG(CASE WHEN discount_applied = 'No'
                      THEN purchase_amount END), 2) AS avg_without_discount,
       COUNT(*) AS orders
FROM customer
GROUP BY category;


-- QUESTION_15: High-revenue but low-rated products (fix quality before reputation hit)
SELECT item_purchased,
       SUM(purchase_amount)           AS revenue,
       ROUND(AVG(review_rating), 2)   AS avg_rating,
       COUNT(*)                       AS orders
FROM customer
GROUP BY item_purchased
HAVING AVG(review_rating) IS NOT NULL
   AND SUM(review_rating IS NOT NULL) >= 5
ORDER BY avg_rating ASC, revenue DESC
LIMIT 10;


-- QUESTION_16: Pareto check — what % of customers drive 80% of current-order revenue?
WITH cume AS (
    SELECT customer_id,
           purchase_amount,
           SUM(purchase_amount) OVER (ORDER BY purchase_amount DESC) AS running_total,
           SUM(purchase_amount) OVER ()                              AS grand_total,
           100.0 * ROW_NUMBER() OVER (ORDER BY purchase_amount DESC)
                 / COUNT(*) OVER ()                                  AS cumulative_pct_customers
    FROM customer
)
SELECT MIN(cumulative_pct_customers) AS pct_customers_for_80pct_revenue
FROM cume
WHERE running_total >= 0.80 * grand_total;

